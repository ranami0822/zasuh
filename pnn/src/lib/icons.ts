export type IconName = keyof typeof icons;

/** 塗りの行を、SVG の path（横に連なる塗りを1つの長方形にまとめる）にする */
export function iconPath(name: IconName): string {
	const def: IconDef = icons[name];
	let rows = def.rows;
	if (!rows && def.mirror) rows = (icons[def.mirror as IconName] as IconDef).rows!.map((r) => [...r].reverse().join(''));
	if (!rows) return '';
	let d = '';
	rows.forEach((row, y) => {
		for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
	});
	return d;
}
