"""UnifontEX を、使う文字ごとの塊に分けて pnn/fonts/ に出力する。

使い方（root 権限では実行しない。仮想環境で）:
    python3 -m venv .venv && .venv/bin/pip install fonttools brotli
    .venv/bin/python pnn/scripts/build-font.py

元は npm の @fontsource/unifontex（OFL-1.1）の woff2。先に `cd pnn && npm install` を済ませておく。
出力した塊は、`unicode-range` で、ページに出た文字が含まれるものだけ読み込まれる。

  base   英数字、かな、日本語の記号、全角形（最初に読む。小さい）
  kanji1 JIS 第1水準の漢字
  kanji2 JIS X 0208 の残り（第2水準の漢字、記号など）
  symbols ラテン・ギリシャ・キリル文字、約物、矢印、図形、ハートなどの記号、異体字選択子
  emoji  絵文字（U+1F000〜1FAFF）
  rest   上のどれにも入らない、フォントの残りすべて（大きい。珍しい文字が出たときだけ読む）
"""
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "node_modules/@fontsource/unifontex/files/unifontex-latin-400-normal.woff2"
OUT = ROOT / "fonts"


def euc_chars(rows):
    out = set()
    for hi in rows:
        for lo in range(0x21, 0x7F):
            try:
                out.add(ord(bytes([hi | 0x80, lo | 0x80]).decode("euc_jp")))
            except UnicodeDecodeError:
                pass
    return out


def ranges(cps):
    cps = sorted(cps)
    runs, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == prev + 1:
            prev = c
            continue
        runs.append((start, prev))
        start = prev = c
    runs.append((start, prev))
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def build(font_cps, name):
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    opts.drop_tables += ["BASE", "GSUB", "GPOS", "GDEF", "FFTM", "PfEd", "TeX "]  # post は必須（ブラウザが拒否する）
    opts.notdef_outline = True
    opts.glyph_names = False
    font = TTFont(SRC)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=font_cps)
    sub.subset(font)
    font["name"].names.sort(key=lambda n: (n.platformID, n.platEncID, n.langID, n.nameID))  # ブラウザの検証は、並び順を見る
    font.flavor = "woff2"
    buf = io.BytesIO()
    font.save(buf)
    (OUT / f"unifontex-{name}.woff2").write_bytes(buf.getvalue())
    print(f"{name}: {len(font_cps)} chars, {len(buf.getvalue()) / 1024:.0f} KB", flush=True)


def main():
    if not SRC.exists():
        sys.exit(f"missing {SRC} (run `npm install` in pnn/)")
    OUT.mkdir(exist_ok=True)
    cmap = set(TTFont(SRC).getBestCmap())

    base = (set(range(0x20, 0x7F)) | set(range(0x3000, 0x3100)) | set(range(0xFF00, 0xFFF0))) & cmap
    jis = euc_chars(range(0x21, 0x75)) & cmap
    kanji1 = (euc_chars(range(0x30, 0x50)) - base) & cmap
    # 約物や記号（…、→、★ など）は、JIS X 0208 に入っていても symbols に入れる（kanji2 を呼ばないため）
    symbols = ((set(range(0xA0, 0x590)) | set(range(0x2000, 0x2C00)) | set(range(0xFE00, 0xFE10))) & cmap) - base - kanji1
    kanji2 = jis - base - kanji1 - symbols
    taken = base | kanji1 | kanji2 | symbols
    emoji = (set(range(0x1F000, 0x1FB00)) & cmap) - taken
    rest = cmap - taken - symbols - emoji
    rest = {c for c in rest if c >= 0xA0}  # 制御文字は除く

    groups = {"base": base, "kanji1": kanji1, "kanji2": kanji2, "symbols": symbols, "emoji": emoji, "rest": rest}
    only = sys.argv[1:]  # 塊の名前を渡すと、その塊だけ作り直す（CSS は常に全部書く）
    for name, cps in groups.items():
        if not only or name in only:
            build(cps, name)

    css = ["/* generated by scripts/build-font.py — do not edit. UnifontEX (OFL-1.1, stgiga) */"]
    for name, cps in groups.items():
        css.append(
            "@font-face {\n"
            "\tfont-family: 'UnifontEX';\n\tfont-style: normal;\n\tfont-weight: 400;\n\tfont-display: swap;\n"
            f"\tsrc: url(./unifontex-{name}.woff2) format('woff2');\n"
            f"\tunicode-range: {ranges(cps)};\n}}"
        )
    (OUT / "unifontex.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print("wrote unifontex.css")


main()
